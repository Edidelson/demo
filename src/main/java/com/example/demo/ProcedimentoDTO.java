package com.example.demo;

public class ProcedimentoDTO {

    private String codigoProcedimento;

    private String	descProcedimento;

    private String convenio;

    private String subgrupo;

    private String grupo;

    private String capitulo;

    private String area;

    private String dtEstimadaProcedimento;


    public String getCodigoProcedimento() {
        return codigoProcedimento;
    }

    public void setCodigoProcedimento(String codigoProcedimento) {
        this.codigoProcedimento = codigoProcedimento;
    }

    public String getDescProcedimento() {
        return descProcedimento;
    }

    public void setDescProcedimento(String descProcedimento) {
        this.descProcedimento = descProcedimento;
    }

    public String getConvenio() {
        return convenio;
    }

    public void setConvenio(String convenio) {
        this.convenio = convenio;
    }

    public String getSubgrupo() {
        return subgrupo;
    }

    public void setSubgrupo(String subgrupo) {
        this.subgrupo = subgrupo;
    }

    public String getGrupo() {
        return grupo;
    }

    public void setGrupo(String grupo) {
        this.grupo = grupo;
    }

    public String getCapitulo() {
        return capitulo;
    }

    public void setCapitulo(String capitulo) {
        this.capitulo = capitulo;
    }

    public String getArea() {
        return area;
    }

    public void setArea(String area) {
        this.area = area;
    }

    public String getDtEstimadaProcedimento() {
        return dtEstimadaProcedimento;
    }

    public void setDtEstimadaProcedimento(String dtEstimadaProcedimento) {
        this.dtEstimadaProcedimento = dtEstimadaProcedimento;
    }
}
